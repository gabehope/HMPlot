// The chart library (TODO 130.4): each src/lib/charts/<name>.js is a chart's whole definition,
// and these functions write what the generator (generate-python-signatures.mjs) derives from it:
// its options-table entry, TypeScript props, Svelte component, the barrel the package exports,
// and its reference page. A built-in template (src/lib/compound/*.js, TODO 130.5) declares its
// signature in its definition too: the generator writes its table entry and props from it.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { definitionKinds, mainKind } from "../src/lib/templates/instantiate.js";

const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const header = (from) =>
  `Generated by scripts/generate-python-signatures.mjs from ${from}; do not edit.`;

/** The charts, in file order: [{ file (the module's basename), definition }]. */
export async function loadCharts(root) {
  const folder = path.join(root, "src/lib/charts");
  const files = fs.existsSync(folder)
    ? fs
        .readdirSync(folder)
        .filter((file) => file.endsWith(".js"))
        .sort()
    : [];
  const charts = [];
  for (const file of files) {
    const definition = (
      await import(pathToFileURL(path.join(folder, file)).href)
    ).default;
    if (!definition?.chart)
      throw Error(
        `src/lib/charts/${file}: its default export is not a defineChart(...) definition.`,
      );
    charts.push({ file, definition });
  }
  return charts;
}

/** Each chart's options-table entry, under its kind (src/lib/scene/options.charts.json). */
export function chartEntries(charts, table) {
  const entries = {};
  for (const { file, definition } of charts) {
    const { kind, chart } = definition;
    if (table.components[kind])
      throw Error(
        `src/lib/charts/${file}: ${kind} is already a component (in src/lib/scene/options.json or a built-in template's signature); name the chart otherwise.`,
      );
    entries[kind] = {
      tier: "charts",
      mark: true,
      // Its settings read as this part's (scene/settings.js), as a built-in template's do.
      mainKind: mainKind(definition),
      group: chart.group,
      summary: chart.summary,
      module: `./charts/generated/${kind}.svelte`,
      use: chart.use,
      omit: chart.omit,
      options: chart.options,
    };
  }
  return entries;
}

/** Each built-in template's options-table entry, under its kind (src/lib/scene/options.templates.json). */
export function templateEntries(templates, table) {
  const entries = {};
  for (const { kind, signature } of templates) {
    if (!signature) continue;
    if (table.components[kind])
      throw Error(
        `src/lib/compound: ${kind} declares its signature, so src/lib/scene/options.json has no entry for it; remove that one.`,
      );
    const { tier, group, summary, use, omit, options } = signature;
    entries[kind] = {
      ...(tier === undefined ? {} : { tier }),
      mark: true,
      group,
      summary,
      ...(use === undefined ? {} : { use }),
      ...(omit === undefined ? {} : { omit }),
      options,
    };
  }
  return entries;
}

// An options-table type as TypeScript writes it.
const tsTypes = {
  channel: "Channel",
  column: "string",
  "column[]": "string[]",
  number: "number",
  boolean: "boolean",
  string: "string",
  color: "string",
  object: "Record<string, unknown>",
  "[number, number]": "[number, number]",
  "number[]": "number[]",
  "string[]": "string[]",
};
function tsType(type, where) {
  if (tsTypes[type]) return tsTypes[type];
  if (type.split(" | ").every((part) => /^"[^"]*"$/.test(part))) return type;
  throw Error(
    `${where}: option type "${type}" has no TypeScript form here; use one of ${Object.keys(tsTypes).join(", ")} or a union of quoted literals, or give the option its TypeScript type as option(type, doc, { ts: "..." }).`,
  );
}
const jsdoc = (text, indent = "") =>
  `${indent}/** ${text.replace(/\*\//g, "*\\/")} */`;

/**
 * A props interface: MarkProps' members for exactly the shared options the table gives the kind
 * (`optionsOf` is the merged table's componentOptions), and its own typed options, so svelte-check
 * accepts what the table lists and nothing else; with `extraProps`, any other prop too.
 */
function propsInterface({ kind, summary, options, types = {}, required, extraProps, forbid = {}, where, optionsOf }) {
  const own = Object.keys(options).filter((name) => options[name].type);
  const shared =
    optionsOf(kind)
      .filter(
        (option) =>
          option.languages !== "python" &&
          !option.setting &&
          !own.includes(option.name) &&
          !Object.hasOwn(forbid, option.name),
      )
      .map((option) => JSON.stringify(option.name))
      .join(" | ") || "never";
  // Python takes its own options (a mark's data) itself; a required option is required here.
  const members = own
    .filter((name) => options[name].languages !== "python")
    .map(
      (name) =>
        `${jsdoc(options[name].doc, "  ")}\n  ${name}${required.has(name) ? "" : "?"}: ${types[name] ?? tsType(options[name].type, `${where}: ${kind}.${name}`)};`,
    );
  const forbidden = Object.entries(forbid).map(([name, message]) => `${jsdoc(message, "  ")}\n  ${name}?: never;`);
  const index = extraProps ? ["  [option: string]: any;"] : [];
  return `${jsdoc(summary)}\nexport interface ${kind}Props extends Pick<MarkProps, ${shared}> {\n${[...index, ...members, ...forbidden].join("\n")}\n}\n`;
}

// The named types the props interfaces use, which the generated file imports: the capitalized
// words outside their docs, string literals and own names.
function typeImports(interfaces, exported) {
  const names = new Set(["MarkProps"]);
  for (const text of interfaces) {
    const kind = text.match(/^export interface (\w+)Props/m)?.[1];
    const code = text.replace(/\/\*\*[\s\S]*?\*\//g, "").replace(/"[^"]*"|'[^']*'/g, "").replace(/^export interface \w+/m, "");
    for (const [name] of code.matchAll(/\b[A-Z]\w*\b/g)) {
      if (["Record", "Array", "Pick"].includes(name)) continue;
      if (exported && !exported.has(name))
        throw Error(`${kind}: its props name the type ${name}, which src/lib/plot/publicTypes.ts does not export; use an exported type in the option's ts.`);
      names.add(name);
    }
  }
  return [...names].sort();
}
// The names publicTypes.ts exports, by its declarations and export lists.
const publicTypeNames = (text) =>
  new Set([...text.matchAll(/^export (?:interface|type|class|enum|const|function) (\w+)/gm)].map((match) => match[1])
    .concat([...text.matchAll(/^export (?:type )?\{([^}]*)\}/gm)].flatMap((match) => match[1].split(",").map((name) => name.trim().split(/\s+as\s+/).pop()).filter(Boolean))));
let exportedTypes;
const publicTypes = () =>
  (exportedTypes ??= publicTypeNames(fs.readFileSync(new URL("../src/lib/plot/publicTypes.ts", import.meta.url), "utf8")));
const typesFile = (from, interfaces) =>
  `// ${header(from)}\nimport type { ${typeImports(interfaces, publicTypes()).join(", ")} } from "../../plot/publicTypes.js";\n\n${interfaces.join("\n")}`;

/** The charts' props types (src/lib/charts/generated/types.ts). */
export function chartTypes(charts, optionsOf) {
  const interfaces = charts.map(({ file, definition }) =>
    propsInterface({
      kind: definition.kind,
      summary: definition.chart.summary,
      options: definition.chart.options,
      types: definition.chart.types,
      required: new Set(Object.keys(definition.required ?? {})),
      where: `src/lib/charts/${file}`,
      optionsOf,
    }),
  );
  return typesFile("src/lib/charts/*.js", interfaces);
}

/** The built-in templates' props types (src/lib/compound/generated/types.ts), re-exported by publicTypes.ts. */
export function templateTypes(templates, optionsOf) {
  const interfaces = templates
    .filter(({ signature }) => signature)
    .map(({ kind, signature, forbid }) =>
      propsInterface({
        kind,
        summary: signature.summary,
        options: signature.options,
        types: signature.types,
        required: new Set(signature.required),
        extraProps: signature.extraProps,
        forbid: forbid ?? {},
        where: `src/lib/compound (${kind})`,
        optionsOf,
      }),
    );
  return typesFile("the signatures in src/lib/compound/*.js", interfaces);
}

/**
 * A chart's Svelte component (src/lib/charts/generated/<Kind>.svelte): the template host given
 * exactly the parts the definition mounts, each from its registry module, and the handle.
 */
export function chartComponent({ file, definition }, registry) {
  const kinds = [...definitionKinds(definition)];
  const imports = kinds.map((kind) => {
    const module = registry.components[kind]?.module;
    if (!module)
      throw Error(
        `src/lib/charts/${file}: ${definition.kind} mounts ${kind}, which is not a public component.`,
      );
    return `  import ${kind} from "../../${module.slice(2)}";`;
  });
  return `<script lang="ts">
  // ${header(`../${file}`)}
${imports.join("\n")}
  import type { ${definition.kind}Props } from "./types.js";
  import TemplateHost from "../../templates/TemplateHost.svelte";
  import definition from "../${file}";
  let props: ${definition.kind}Props = $props();
  let host = $state<any>();
  export const getLegendSource = () => host?.getLegendSource();
  export const getMark = () => host?.getMark();
  export const whenSettled = () => host?.whenSettled();
  export const subscribeSettings = (listener: (values: Record<string, unknown>) => void) => host?.subscribeSettings(listener) ?? (() => {});
</script>

<TemplateHost {definition} parts={{ ${kinds.join(", ")} }} {props} bind:this={host} />
`;
}

/** The package's chart exports (src/lib/charts/generated/index.ts), re-exported by src/lib/charts/index.ts. */
export function chartBarrel(charts) {
  return `// ${header("src/lib/charts/*.js")}\n${charts
    .map(
      ({ definition: { kind } }) =>
        `export { default as ${kind} } from "./${kind}.svelte";\nexport type { ${kind}Props } from "./types.js";`,
    )
    .join("\n")}\n`;
}

/** A chart's reference page prose (src/routes/content/reference/<id>.svx). */
export function chartPage({ file, definition }) {
  const usage = definition.chart.usage ? `\n\n${definition.chart.usage}` : "";
  return `<!-- ${header(`src/lib/charts/${file}`)} -->\n## Usage${usage}\n\n${definition.kind} is a chart: a template over public components, defined in one file, src/lib/charts/${file}.\n`;
}

/** Every file the charts and the built-in templates' signatures generate, by path under the repository root. */
export function chartOutputs(charts, templates, table, registry, optionsOf) {
  const templateTable = templateEntries(templates, table);
  const outputs = [
    [
      "src/lib/scene/options.charts.json",
      JSON.stringify(chartEntries(charts, { components: { ...table.components, ...templateTable } }), null, 2) + "\n",
    ],
    [
      "src/lib/scene/options.templates.json",
      JSON.stringify(templateTable, null, 2) + "\n",
    ],
    ["src/lib/charts/generated/types.ts", chartTypes(charts, optionsOf)],
    ["src/lib/compound/generated/types.ts", templateTypes(templates, optionsOf)],
    ["src/lib/charts/generated/index.ts", chartBarrel(charts)],
  ];
  for (const chart of charts) {
    outputs.push([
      `src/lib/charts/generated/${chart.definition.kind}.svelte`,
      chartComponent(chart, registry),
    ]);
    outputs.push([
      `src/routes/content/reference/${kebab(chart.definition.kind)}.svx`,
      chartPage(chart),
    ]);
  }
  return outputs;
}
